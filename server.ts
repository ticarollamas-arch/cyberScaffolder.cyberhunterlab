async function getYoutubeVideoMetadata(videoUrl: string): Promise<{ title: string; author: string }> {
  // Extract Video ID if possible
  let videoId = "";
  try {
    const regExp = /^.*(youtu.be\/|v\/|u\/\w\/|embed\/|watch\?v=|\&v=|shorts\/)([^#\&\?]*).*/;
    const match = videoUrl.match(regExp);
    if (match && match[2].length === 11) {
      videoId = match[2];
    }
  } catch (e) {
    console.warn("[Youtube Meta] Erro ao extrair Video ID:", e);
  }

  // 1. Try oEmbed
  try {
    const encodedUrl = encodeURIComponent(videoUrl);
    const oembedUrl = `https://www.youtube.com/oembed?url=${encodedUrl}&format=json`;
    const response = await fetch(oembedUrl, {
      headers: {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Accept-Language": "pt-BR,pt;q=0.9,en-US;q=0.8,en;q=0.7"
      }
    });
    if (response.ok) {
      const data: any = await response.json();
      if (data.title && data.title !== "Curso do YouTube") {
        return {
          title: data.title,
          author: data.author_name || "Criador de Conteúdo"
        };
      }
    }
  } catch (err) {
    console.warn("[Youtube Meta] Falha ao obter metadados via oEmbed:", err);
  }

  // 2. Try scraping the watch page (if video ID is available)
  if (videoId) {
    try {
      console.log(`[Youtube Meta] Tentando raspagem direta da página do vídeo para ID: ${videoId}`);
      const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;
      const response = await fetch(watchUrl, {
        headers: {
          "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
          "Accept-Language": "pt-BR,pt;q=0.9,en-US;q=0.8,en;q=0.7"
        }
      });
      if (response.ok) {
        const html = await response.text();
        
        let title = "";
        const ogTitleMatch = html.match(/<meta\s+property="og:title"\s+content="([^"]+)"/i) || 
                             html.match(/<meta\s+name="title"\s+content="([^"]+)"/i);
        if (ogTitleMatch && ogTitleMatch[1]) {
          title = ogTitleMatch[1];
        } else {
          const titleTagMatch = html.match(/<title>(.*?)<\/title>/i);
          if (titleTagMatch && titleTagMatch[1]) {
            title = titleTagMatch[1].replace(/\s*-\s*YouTube/i, "");
          }
        }

        let author = "";
        const ogChannelMatch = html.match(/<link\s+itemprop="name"\s+content="([^"]+)"/i) ||
                               html.match(/<meta\s+itemprop="name"\s+content="([^"]+)"/i);
        if (ogChannelMatch && ogChannelMatch[1]) {
          author = ogChannelMatch[1];
        } else {
          const ownerMatch = html.match(/"ownerChannelName"\s*:\s*"([^"]+)"/i) ||
                             html.match(/"author"\s*:\s*"([^"]+)"/i);
          if (ownerMatch && ownerMatch[1]) {
            author = ownerMatch[1];
          }
        }

        title = title.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&').trim();
        author = author.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&').trim();

        if (title && title !== "YouTube") {
          console.log(`[Youtube Meta] Título obtido via raspagem HTML: "${title}" por "${author || "Criador"}"`);
          return {
            title,
            author: author || "Criador de Conteúdo"
          };
        }
      }
    } catch (scrapeErr) {
      console.warn("[Youtube Meta] Falha ao raspar a página de vídeo diretamente:", scrapeErr);
    }
  }

  return {
    title: "Curso Avançado sobre o Tema Solicitado",
    author: "Canal do YouTube"
  };
}

